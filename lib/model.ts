// Token Radar — the scoring model (radar-2).
//
// One sealed snapshot in, one ranked board out. The board answers a single
// question: "which protocol that records no token yet is worth farming next,
// and what do I do about it?" Nothing in here names a protocol by hand.
// Every row is scored by the same function, from the snapshot's own figures
// only: TVL, 7-day change, age, chain count and category. A protocol below
// the watchlist floor is not worse than one on it — the floor is where the
// house started looking, and the early rows are the radar's whole point.
//
// Implied value, stated in full so the dashboard can show its working:
//
//   base        = tvl_usd x base_multiple            (0.22 here)
//   growth      = clamp(change_7d, -50, 150) per cent
//   growthMult  = 1 + (growth / 100) x growth_weight  (0.6 here)
//   maturity    = maturity_floor
//                 + min(age_days, 1460) / 1460 x maturity_range
//                 (0.70 + up to 0.30; unknown age counts as 365 days)
//   chainMult   = 1 + min(chains - 1, 4) x 0.03       (breadth pays a little)
//   categoryMult= the category's factor, 1.00 to 1.10 (see CATEGORY_FACTOR)
//   implied     = max(1, round(base x growthMult x maturity x chainMult x categoryMult))
//
// The category factor is the only judgement call, and it is deliberately
// small: categories whose tokens have historically launched at a larger
// share of TVL (exchanges' own venues excluded — they are not farmable
// pre-token candidates) get up to +10%. It never overrides size, growth or
// age; it only breaks near-ties in a stated direction.
//
// A farm plan is generated per row from the same record — category, first
// chain, TVL tier and age — never from a hand-kept list of names.

/** One protocol as the sealed snapshot carries it: exactly ten fields. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole sealed snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

